import type {
  GeneratedContentData,
  RouteIndexEntry,
} from "@shared/content/generated-contract"
import type { Scene } from "@shared/content/types"

type PreparedSceneFile = { value: Scene }

/** 게시된 Scene의 부모 경로를 계산해 경로순 Route Index를 만든다. */
export function buildRouteIndex(
  files: readonly PreparedSceneFile[]
): RouteIndexEntry[] {
  const published = files.filter(({ value }) => value.status === "published")
  const scenesById = new Map(published.map((item) => [item.value.id, item]))
  const paths = new Map<string, string>()

  /** 부모 Route를 먼저 해석해 전체 URL을 계산하고 같은 결과를 재사용한다. */
  function resolveRoute(sceneId: string): string {
    const cached = paths.get(sceneId)
    if (cached) return cached
    const item = scenesById.get(sceneId)
    if (!item) {
      throw new Error(
        `Published route references unavailable Scene: ${sceneId}`
      )
    }
    const route = item.value.parentId
      ? `${resolveRoute(item.value.parentId)}/${item.value.slug}`
      : `/explore/${item.value.slug}`
    paths.set(sceneId, route)
    return route
  }

  return published
    .map(({ value }) => ({
      id: value.id,
      title: value.title,
      path: resolveRoute(value.id),
      ...(value.parentId ? { parentId: value.parentId } : {}),
    }))
    .sort((left, right) => left.path.localeCompare(right.path))
}

/** 완성된 runtime content record를 단일 생성 TypeScript 모듈로 직렬화한다. */
export function renderContentData(data: GeneratedContentData) {
  return `import type { GeneratedContentData } from "@shared/content/generated-contract"\n\n// Generated by scripts/build-content-index.ts. Do not edit manually.\nexport const contentData: GeneratedContentData = ${JSON.stringify(data, null, 2)}\n`
}
